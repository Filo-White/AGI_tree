"""
Answer Quality Metrics — LLM Judge (Rubric-based evaluation).
"""
import json
import os
import random
import sys
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parent.parent.parent.parent / "backend"
sys.path.insert(0, str(BACKEND_DIR))

JUDGE_PROMPT = """You are an impartial evaluator of document question-answering systems.

You will receive:
1. A user question.
2. A reference answer or expected answer points.
3. The answer generated by a system.
4. Evidence text retrieved or selected by the system.
5. A flag indicating whether the question is answerable from the document.

Evaluate the system answer only with respect to the reference answer and the provided evidence.

Use the following 1-5 scales:

Correctness:
1 = incorrect or contradicts the document
2 = mostly incorrect
3 = partially correct
4 = mostly correct
5 = fully correct

Faithfulness:
1 = unsupported or hallucinated
2 = weakly supported
3 = partially supported
4 = mostly supported
5 = fully supported by the document

Completeness:
1 = misses almost all required points
2 = misses major required points
3 = covers some required points
4 = covers most required points
5 = covers all required points

Relevance:
1 = does not answer the question
2 = mostly irrelevant
3 = partially relevant
4 = mostly relevant
5 = directly answers the question

For unanswerable questions, also evaluate abstention_correct:
true = the system correctly states that the document does not provide enough information
false = the system incorrectly gives a substantive answer or hallucinates

Return only valid JSON with this schema:
{"correctness": 1, "faithfulness": 1, "completeness": 1, "relevance": 1, "abstention_correct": null, "short_rationale": "..."}"""

# Method name anonymization map
_ANON_NAMES = {
    "dat_full": "System_A",
    "flat_rag": "System_B",
    "section_rag": "System_C",
    "long_context": "System_D",
    "dat_no_expansion": "System_E",
    "dat_parent_only": "System_F",
    "dat_no_self_scoring": "System_G",
}


async def judge_answer(
    query: str,
    reference_answer: str,
    expected_points: list[str],
    system_answer: str,
    evidence_text: str,
    answerable: bool,
    judge_model: str = None,
    anonymize: bool = True,
    method_name: str = "",
) -> dict:
    """Run LLM judge on a single answer. Returns judge scores dict."""
    from openai import AsyncOpenAI
    from dotenv import load_dotenv
    load_dotenv(BACKEND_DIR / ".env")

    if judge_model is None:
        judge_model = os.getenv("JUDGE_MODEL", "gpt-5.4-nano-2026-03-17")

    client = AsyncOpenAI(api_key=os.getenv("OPENAI_API_KEY"))

    display_method = _ANON_NAMES.get(method_name, method_name) if anonymize else method_name
    points_str = "\n".join(f"- {p}" for p in expected_points) if expected_points else "N/A"

    user_message = (
        f"Question: {query}\n\n"
        f"Reference answer: {reference_answer}\n\n"
        f"Expected answer points:\n{points_str}\n\n"
        f"System ({display_method}) answer: {system_answer}\n\n"
        f"Evidence provided to the system:\n{evidence_text[:3000]}\n\n"
        f"Answerable: {answerable}"
    )

    try:
        response = await client.chat.completions.create(
            model=judge_model,
            messages=[
                {"role": "system", "content": JUDGE_PROMPT},
                {"role": "user", "content": user_message},
            ],
            temperature=0.0,
            max_completion_tokens=300,
        )
        raw = response.choices[0].message.content.strip()
        raw = raw.removeprefix("```json").removesuffix("```").strip()
        scores = json.loads(raw)
        return scores
    except (json.JSONDecodeError, Exception) as e:
        return {
            "correctness": None, "faithfulness": None, "completeness": None,
            "relevance": None, "abstention_correct": None,
            "short_rationale": f"Judge error: {e}",
        }


def compute_answer_quality_summary(judge_results: list[dict]) -> dict:
    """Compute aggregate answer quality metrics from judge results."""
    metrics = ["correctness", "faithfulness", "completeness", "relevance"]
    summary = {}

    for m in metrics:
        values = [r[m] for r in judge_results if r.get(m) is not None]
        if values:
            summary[f"{m}_mean"] = round(sum(values) / len(values), 3)
            summary[f"{m}_std"] = round((sum((v - summary[f"{m}_mean"])**2 for v in values) / len(values))**0.5, 3)
        else:
            summary[f"{m}_mean"] = None
            summary[f"{m}_std"] = None

    # Abstention accuracy
    abstention_results = [r for r in judge_results if r.get("abstention_correct") is not None]
    if abstention_results:
        correct = sum(1 for r in abstention_results if r["abstention_correct"])
        summary["abstention_accuracy"] = round(correct / len(abstention_results), 3)
    else:
        summary["abstention_accuracy"] = None

    summary["n_judged"] = len(judge_results)
    return summary
